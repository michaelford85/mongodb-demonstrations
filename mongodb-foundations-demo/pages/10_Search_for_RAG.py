"""Section ⑨: Search for RAG — retrieval-augmented generation, end to end."""

import streamlit as st
from pymongo.errors import PyMongoError

from lib.explain import to_mongosh
from lib.rag import answer
from lib.search_config import RAG_TOP_K, generation_available, namespace
from lib.search_data import RAG_QUESTIONS
from lib.ui import (connection_guard, cue, page_header, page_setup,
                    presenter_mode, prose, search_data_guard,
                    search_index_guard, sidebar_reset, synthetic_note, table,
                    takeaway)

page_setup("Search for RAG", icon="⑨")
presenter_mode()
connection_guard()
sidebar_reset()
search_data_guard()
search_index_guard()

page_header("⑨", "Search for RAG",
            "MongoDB is the retrieval half of RAG. Watch a question become "
            "grounding, then a prompt, then an answer.")

ns = namespace()
st.caption("Retrieval runs over `{database}.{collection}` using the same Atlas "
           "Search indexes as section ⑧.".format(**ns))

controls = st.columns([3, 1, 1])
question = controls[0].selectbox(
    "Question (each is answerable only from the seeded corpus)",
    [q["q"] for q in RAG_QUESTIONS])
strategy = controls[1].radio("Retrieval", ["hybrid", "semantic"],
                             help="How the grounding chunks are retrieved.")
k = controls[2].select_slider("Top-k", [2, 3, 4, 5, 6], value=RAG_TOP_K)

question = st.text_input("…or type your own", value=question)

gen_on = generation_available()
do_generate = st.toggle(
    "Generate the answer with an LLM", value=gen_on, disabled=not gen_on,
    help="Optional. Retrieval and the prompt always run; generation needs a "
         "GEN_API_KEY.")
if not gen_on:
    st.caption("💡 No generation key configured — the section still shows the "
               "retrieved grounding and the exact prompt, which is the part "
               "MongoDB powers. Set `GEN_API_KEY` in `.env` to also generate.")

if st.button("▶︎ Run RAG", type="primary"):
    try:
        st.session_state["rag"] = answer(
            question, strategy=strategy, k=k, do_generate=do_generate)
    except (PyMongoError, RuntimeError) as exc:
        st.error("Retrieval failed: {}".format(exc))
        st.session_state["rag"] = None

result = st.session_state.get("rag")
if result:
    step1, step2, step3 = st.tabs(
        ["① Retrieve (MongoDB)", "② Ground & prompt", "③ Generate (LLM)"])

    with step1:
        st.markdown("#### The retrieved grounding")
        st.success("{} chunk(s) retrieved via {} search."
                   .format(len(result["chunks"]), result["strategy"]))
        table([{"ref": c["ref"], "doc": c["doc_title"], "section": c["section"],
                "chunk": c["chunk_index"]} for c in result["citations"]],
              "Nothing retrieved.")
        st.markdown("**The exact retrieval aggregation — paste into `mongosh`:**")
        st.code(to_mongosh(result["pipeline"]), language="javascript")
        cue("This is the whole MongoDB contribution to RAG: turn a natural "
            "question into the few passages worth putting in the prompt.")

    with step2:
        st.markdown("#### Grounded context")
        st.caption("Only these passages are given to the model. The answer must "
                   "come from them, and must cite them by number.")
        st.text_area("Context", result["context"], height=220)
        st.markdown("#### The exact prompt")
        st.code(result["prompt"], language="markdown")

    with step3:
        st.markdown("#### The generated answer")
        if result["generated"]:
            st.markdown(result["generated"])
            st.caption("Generated by the configured LLM from ONLY the passages "
                       "above. Cross-check each bracketed citation against "
                       "step ①.")
        elif result["generation_error"]:
            st.warning("Generation was requested but could not run: {}"
                       .format(result["generation_error"]))
        else:
            st.info("Generation is off or unconfigured. Retrieval and the "
                    "prompt above are the MongoDB-powered half of RAG; the "
                    "answer step is any LLM, shown here for completeness.")

prose(
    "**Where MongoDB starts and stops.** RAG is retrieve-then-generate. MongoDB "
    "owns retrieval: vector or hybrid search over the chunked corpus turns a "
    "question into a small, relevant, citeable context. The app assembles that "
    "context and the exact prompt. Generation — the only non-MongoDB step — is "
    "any LLM, and it is optional here on purpose, because the retrieval quality "
    "is what determines whether the answer can be grounded at all.\n\n"
    "**Why chunking and Automated Embedding matter.** The corpus is chunked at "
    "seed time, the way a real pipeline chunks source documents, so each "
    "retrieved passage is small enough to be a precise citation. Because the "
    "vector index is `autoEmbed`, both the chunks and the question are embedded "
    "by Atlas with the same model — there is no separate embedding service to "
    "operate or keep in sync.\n\n"
    "**Grounding is the guardrail.** The system prompt restricts the model to "
    "the retrieved passages and requires citations, so a wrong or missing "
    "retrieval shows up as *“I don’t have that information”* rather than a "
    "confident fabrication.")

takeaway("RAG = retrieve (MongoDB) + generate (any LLM). Good retrieval — "
         "chunked, autoEmbedded, hybrid — is what makes the generated answer "
         "trustworthy and citeable.")

synthetic_note()
