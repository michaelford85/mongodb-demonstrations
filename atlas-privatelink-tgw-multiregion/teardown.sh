#!/usr/bin/env bash
# Destroys the AWS side of the lab.
#
# The Transit Gateways, the peering attachment, the interface endpoints and the
# VPCs all carry lifecycle { prevent_destroy = true } so that a stray
# `terraform destroy` cannot take them out. This script is the documented,
# deliberate override: it writes Terraform override files that set
# prevent_destroy = false, runs the destroy, and removes the override files
# again - whether the destroy succeeded, failed or was interrupted.
#
# Nothing Atlas-side is touched. Delete the Atlas private endpoints from Atlas
# afterwards, or they will sit there pointing at interface endpoints that no
# longer exist.
set -euo pipefail

OVERRIDE_FILES=(
  "./terraform/zz_destroy_override.tf"
  "./terraform/modules/transit-gateway/zz_destroy_override.tf"
  "./terraform/modules/hub-vpc/zz_destroy_override.tf"
  "./terraform/modules/client-vpc/zz_destroy_override.tf"
)

cleanup_overrides() {
  rm -f "${OVERRIDE_FILES[@]}"
}

# ── Preflight ──────────────────────────────────────────────────────────────────

for tool in terraform jq aws; do
  if ! command -v "$tool" &>/dev/null; then
    echo "ERROR: $tool not found."
    exit 1
  fi
done

if [ ! -f .env ]; then
  echo "ERROR: .env not found."
  exit 1
fi

if [ ! -f terraform/terraform.tfstate ] && [ ! -d terraform/.terraform ]; then
  echo "ERROR: no Terraform state here. Nothing to destroy."
  exit 1
fi

set -a
# shellcheck source=/dev/null
source .env
set +a

# ── Confirmation ───────────────────────────────────────────────────────────────

cat <<CONFIRM

WARNING: this permanently destroys the lab, including resources that are
protected by prevent_destroy:

  - both Transit Gateways and their route tables
  - the inter-region Transit Gateway peering attachment
  - every Atlas interface VPC endpoint
  - the client VPC and both hub VPCs
  - the test VM

Deleting an interface endpoint leaves the matching Atlas private endpoint
pointing at nothing. Remove it in Atlas afterwards.

Prefix: ${NAME_PREFIX:-<unset>}

CONFIRM

if [ "${ALLOW_DESTROY:-}" != "yes" ]; then
  read -r -p "Type the name prefix (${NAME_PREFIX:-<unset>}) to confirm destruction: " confirm
  if [ "$confirm" != "${NAME_PREFIX:-}" ]; then
    echo "Name prefix did not match. Aborting."
    exit 1
  fi
fi

# ── Export as TF_VAR_* ─────────────────────────────────────────────────────────

EXTRA_TAGS="${EXTRA_TAGS:-}"
[ -n "$EXTRA_TAGS" ] || EXTRA_TAGS="{}"

export TF_VAR_name_prefix="$NAME_PREFIX"
export TF_VAR_tag_project="$TAG_PROJECT"
export TF_VAR_tag_environment="$TAG_ENVIRONMENT"
export TF_VAR_tag_owner="$TAG_OWNER"
export TF_VAR_tag_purpose="$TAG_PURPOSE"
export TF_VAR_extra_tags="$EXTRA_TAGS"
export TF_VAR_hubs="$HUBS"
export TF_VAR_client="$(echo "$CLIENT" | jq --argjson egress "$(echo "${CLIENT_INTERNET_EGRESS:-true}" | tr '[:upper:]' '[:lower:]')" '.internet_egress_enabled = $egress')"
export TF_VAR_allow_single_az_endpoints="${ALLOW_SINGLE_AZ_ENDPOINTS:-false}"
# Defaults are assigned on their own lines, not inside ${VAR:-...}: brace and
# backslash escaping inside a parameter expansion differs between shells, and
# a stray backslash reaches Terraform as an invalid character.
TEST_PORTS="${TEST_PORTS:-}"
[ -n "$TEST_PORTS" ] || TEST_PORTS='[27017]'

TEST_PORT_SCAN="${TEST_PORT_SCAN:-}"
[ -n "$TEST_PORT_SCAN" ] || TEST_PORT_SCAN='{"start": 1024, "end": 1060}'

SPOKES="${SPOKES:-}"
[ -n "$SPOKES" ] || SPOKES='{}'

export TF_VAR_spokes="$SPOKES"
export TF_VAR_ram_allow_external_principals="${RAM_ALLOW_EXTERNAL_PRINCIPALS:-false}"
export TF_VAR_test_ports="$TEST_PORTS"
export TF_VAR_test_port_scan_range="$TEST_PORT_SCAN"
export TF_VAR_mongosh_s3_uri="${MONGOSH_S3_URI:-}"

# ── Lift prevent_destroy for the duration of this run ──────────────────────────
#
# Terraform merges the lifecycle block of an *_override.tf file into the
# original resource argument by argument, so these files change nothing except
# prevent_destroy.

trap cleanup_overrides EXIT
cleanup_overrides

cat >./terraform/zz_destroy_override.tf <<'EOF'
# Generated by ./teardown.sh. Deleted again when it exits. Do not commit.
resource "aws_ec2_transit_gateway_peering_attachment" "a_to_b" {
  lifecycle {
    prevent_destroy = false
  }
}

resource "aws_ec2_transit_gateway_peering_attachment_accepter" "b_from_a" {
  lifecycle {
    prevent_destroy = false
  }
}
EOF

cat >./terraform/modules/transit-gateway/zz_destroy_override.tf <<'EOF'
# Generated by ./teardown.sh. Deleted again when it exits. Do not commit.
resource "aws_ec2_transit_gateway" "this" {
  lifecycle {
    prevent_destroy = false
  }
}
EOF

cat >./terraform/modules/hub-vpc/zz_destroy_override.tf <<'EOF'
# Generated by ./teardown.sh. Deleted again when it exits. Do not commit.
resource "aws_vpc" "this" {
  lifecycle {
    prevent_destroy = false
  }
}

resource "aws_vpc_endpoint" "atlas" {
  lifecycle {
    prevent_destroy = false
  }
}
EOF

cat >./terraform/modules/client-vpc/zz_destroy_override.tf <<'EOF'
# Generated by ./teardown.sh. Deleted again when it exits. Do not commit.
resource "aws_vpc" "this" {
  lifecycle {
    prevent_destroy = false
  }
}
EOF

# ── Destroy ────────────────────────────────────────────────────────────────────

echo ""
echo "Destroying..."
terraform -chdir=terraform init -upgrade
terraform -chdir=terraform destroy -auto-approve

echo ""
echo "AWS resources destroyed. Remember to delete the Atlas private endpoints"
echo "for these regions in the Atlas UI or through the Atlas Admin API."
